"""Builds Data/Areas.lua from ForeverWorldMap's export of the client's
WorldMapOverlay tables: per UI map, the first file ID of every exploration
overlay (the ID C_MapExplorationInfo.GetExploredMapTextures reports first)."""
import re, sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
build = re.search(r'OVERLAY_BUILD = "([^"]+)"', text).group(1)
maps, cur = [], None
for line in text.splitlines():
    m = re.match(r'\s{4}\[(\d+)\] = \{ -- (.+)$', line)
    if m:
        cur = (int(m.group(1)), m.group(2).strip(), []); maps.append(cur); continue
    o = re.match(r'\s{8}\{([^}]*)\}', line)
    if o and cur:
        cur[2].append(int(o.group(1).split(",")[5]))
out = ["local _, ns = ...", "",
       "-- Generated by tools/export_areas.py. Do not edit by hand.",
       "-- Every exploration area of each zone, by UI map: the first file ID of",
       "-- the area's overlay, as C_MapExplorationInfo.GetExploredMapTextures gives it.",
       "-- Source: the client's WorldMapOverlay tables, build " + build + ".",
       'ns.AREA_BUILD = "' + build + '"', "ns.Areas = {"]
for mid, name, ids in maps:
    out.append("    [%d] = { -- %s" % (mid, name))
    out.append("        " + ", ".join(str(i) for i in ids) + ",")
    out.append("    },")
out.append("}")
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(maps), "maps", sum(len(m[2]) for m in maps), "areas")

-- Builds Data/Rares.lua: every open-world rare creature on WoW Forever, with
-- its name, where it spawns, and its level, for the Bestiary to list (and
-- black out) before anyone has found it.
--
-- Source: the rare records of Polestar Codex (GPL-3.0), which Polestar built
-- from pfQuest (MIT), QuestieDB (Questie-Forever) and the client's own map
-- tables; facts only (ids, names, levels, coordinates). See README.
--
-- Run from the addon folder with any Lua 5.1+:
--   luatex --luaonly tools/export_rares.lua <path to Polestar_Codex> Data/Rares.lua

local dir, out = arg[1], arg[2]
assert(dir and out, "usage: export_rares.lua <Polestar_Codex dir> <out file>")

local blobs = {}
Polestar = {
	Codex = {
		Register = function(group, names, recs)
			if group == "rare" then blobs[#blobs + 1] = { names = names, recs = recs } end
		end,
		RegisterIndex = function() end,
	},
}

local version = "?"
local toc = io.open(dir .. "/Polestar_Codex.toc")
if toc then
	for line in toc:lines() do
		local v = line:match("^## Version:%s*(.-)%s*$")
		if v then version = v end
	end
	toc:close()
end

for i = 1, 9 do
	local path = dir .. "/Rares" .. i .. ".lua"
	local fh = io.open(path)
	if fh then
		fh:close()
		dofile(path)
	end
end
assert(#blobs > 0, "no rare records found in " .. dir)

-- s split by sep, empty fields kept
local function split(s, sep)
	local t = {}
	for f in (s .. sep):gmatch("(.-)" .. sep:gsub("%p", "%%%0")) do t[#t + 1] = f end
	return t
end

local rares, count, skipped = {}, 0, 0
for _, b in ipairs(blobs) do
	local names = {}
	for line in b.names:gmatch("[^\n]+") do
		local id, _, name = line:match("^(%d+)\t([^\t]*)\t(.*)$")
		if id then names[tonumber(id)] = name end
	end
	for line in (b.recs or ""):gmatch("[^\n]+") do
		local id, rec = line:match("^(%d+)\t(.*)$")
		id = tonumber(id)
		if id and names[id] then
			local t = split(rec, ";")
			local n = #t
			-- Trailing title ("t...") and spawn heights ("z...") fields.
			if n >= 8 and t[n]:sub(1, 1) == "t" then n = n - 1 end
			if n >= 1 and t[n]:sub(1, 1) == "z" then n = n - 1 end
			local instance = t[5] and t[5] ~= ""
			local spawn = t[8] and split(t[8], ",")
			local map = spawn and tonumber(spawn[1])
			local x, y = spawn and tonumber(spawn[3]), spawn and tonumber(spawn[4])
			if instance or not map then
				skipped = skipped + 1
			else
				rares[#rares + 1] = {
					id = id, name = names[id], map = map,
					x = x and x / 10, y = y and y / 10,
					level = tonumber(t[1]), levelMax = tonumber(t[2]),
					elite = (t[4] or ""):find("e", 1, true) ~= nil,
				}
				count = count + 1
			end
		end
	end
end
table.sort(rares, function(a, b) return a.id < b.id end)

local function q(s) return ("%q"):format(s):gsub("\\\n", "\\n") end
local lines = {
	"local _, ns = ...",
	"",
	"-- Generated by tools/export_rares.lua. Do not edit by hand.",
	"-- Every open-world rare creature on WoW Forever: id = { name, map, x, y, level, levelMax, elite }.",
	"-- Source: Polestar Codex " .. version .. " (GPL-3.0), built by Polestar from pfQuest (MIT),",
	"-- QuestieDB (Questie-Forever) and the client's map tables. Facts only; credited in README.",
	('ns.RARE_SOURCE = "Polestar Codex %s"'):format(version),
	"ns.RareList = {",
}
for _, r in ipairs(rares) do
	lines[#lines + 1] = ("\t[%d] = { %s, %d, %s, %s, %s, %s, %s },"):format(
		r.id, q(r.name), r.map,
		r.x and ("%.1f"):format(r.x) or "nil", r.y and ("%.1f"):format(r.y) or "nil",
		r.level and tostring(r.level) or "nil", r.levelMax and tostring(r.levelMax) or "nil",
		r.elite and "true" or "false")
end
lines[#lines + 1] = "}"
local fh = assert(io.open(out, "w"))
fh:write(table.concat(lines, "\n"), "\n")
fh:close()
print(("%d rares written, %d in dungeons or without a place skipped"):format(count, skipped))
